function buildSocialLesson(seed: SocialTopicSeed): Lesson {
  return {
    id: seed.id,
    grade: seed.grade,
    subjectId: 'social',
    title: seed.title,
    subtitle: seed.subtitle,
    trimester: seed.trimester,
    durationMinutes: 4,
    simType: 'social_heritage',
    simTitle: `مختبر ${seed.branch} التونسي`,
    simDescription: 'تنقّل بين الخريطة والخط الزمني وميثاق المواطنة قبل الإجابة عن الأنشطة المبسطة.',
    supportTip: seed.supportTip,
    easyTrack: true,
    steps: [
      {
        title: seed.step1Title,
        instruction: seed.step1Instruction,
        takeaway: seed.step1Takeaway,
      },
      {
        title: seed.step2Title,
        instruction: seed.step2Instruction,
        takeaway: seed.step2Takeaway,
      },
    ],
    exercises: [
      {
        id: `${seed.id}-e1`,
        type: 'choice',
        prompt: seed.q1Prompt,
        options: seed.q1Options,
        correctIndex: 0,
        hint: seed.q1Hint,
        explanation: seed.q1Exp,
      },
      {
        id: `${seed.id}-e2`,
        type: 'fill_blank',
        prompt: 'أكمل العبارة الصحيحة بما يناسب درس اليوم:',
        beforeBlank: seed.q2Before,
        afterBlank: seed.q2After,
        choices: seed.q2Choices,
        correctChoice: seed.q2Correct,
        hint: seed.q2Hint,
        explanation: seed.q2Exp,
      },
      {
        id: `${seed.id}-e3`,
        type: 'choice',
        prompt: seed.q3Prompt,
        options: seed.q3Options,
        correctIndex: 0,
        hint: seed.q3Hint,
        explanation: seed.q3Exp,
      },
      {
        id: `${seed.id}-e4`,
        type: 'classify',
        prompt: 'صنّف البطاقات التالية بتركيز في المجموعة المناسبة:',
        binALabel: seed.q4BinA,
        binBLabel: seed.q4BinB,
        items: seed.q4Items,
        hint: seed.q4Hint,
        explanation: seed.q4Exp,
      },
      {
        id: `${seed.id}-e5`,
        type: 'order',
        prompt: seed.q5OrderPrompt,
        tokens: seed.q5Tokens,
        correctOrder: seed.q5CorrectOrder,
        hint: seed.q5Hint,
        explanation: seed.q5Exp,
      },
    ],
  };
}

