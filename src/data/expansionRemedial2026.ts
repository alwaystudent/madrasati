import { Lesson, GradeLevel, SimulationType, SubjectId } from '../types/curriculum';

interface RemedialSpec {
  id: string;
  grade: GradeLevel;
  subjectId: SubjectId;
  trimester: 'الثلاثي الأول' | 'الثلاثي الثاني' | 'الثلاثي الثالث';
  title: string;
  subtitle: string;
  supportTip: string;
  simType: SimulationType;
  simTitle: string;
  simDescription: string;
  durationMinutes: number;
  step1Title: string;
  step1Inst: string;
  step1Takeaway: string;
  step2Title: string;
  step2Inst: string;
  step2Takeaway: string;
  q1Prompt: string;
  q1Options: string[];
  q1Correct: number;
  q1Hint: string;
  q1Exp: string;
  q2Prompt: string;
  q2Options: string[];
  q2Correct: number;
  q2Hint: string;
  q2Exp: string;
  q3Before: string;
  q3After: string;
  q3Choices: string[];
  q3Correct: string;
  q3Hint: string;
  q3Exp: string;
  q4Prompt: string;
  q4BinA: string;
  q4BinB: string;
  q4Items: { id: string; label: string; targetBin: 'A' | 'B' }[];
  q4Hint: string;
  q4Exp: string;
  q5Prompt: string;
  q5Tokens: string[];
  q5Order: string[];
  q5Hint: string;
  q5Exp: string;
  ltr?: boolean;
}

function buildRemedialLesson(s: RemedialSpec): Lesson {
  return {
    id: s.id,
    grade: s.grade,
    subjectId: s.subjectId,
    trimester: s.trimester,
    title: s.title,
    subtitle: s.subtitle,
    supportTip: s.supportTip,
    easyTrack: true,
    durationMinutes: s.durationMinutes,
    simType: s.simType,
    simTitle: s.simTitle,
    simDescription: s.simDescription,
    steps: [
      {
        title: s.step1Title,
        instruction: s.step1Inst,
        takeaway: s.step1Takeaway,
      },
      {
        title: s.step2Title,
        instruction: s.step2Inst,
        takeaway: s.step2Takeaway,
      },
    ],
    exercises: [
      {
        id: `${s.id}-e1`,
        type: 'choice',
        prompt: s.q1Prompt,
        options: s.q1Options,
        correctIndex: s.q1Correct,
        hint: s.q1Hint,
        explanation: s.q1Exp,
        ltr: s.ltr,
      },
      {
        id: `${s.id}-e2`,
        type: 'choice',
        prompt: s.q2Prompt,
        options: s.q2Options,
        correctIndex: s.q2Correct,
        hint: s.q2Hint,
        explanation: s.q2Exp,
        ltr: s.ltr,
      },
      {
        id: `${s.id}-e3`,
        type: 'fill_blank',
        prompt: 'أكمل الفراغ لتثبيت المهارة الأساسية:',
        beforeBlank: s.q3Before,
        afterBlank: s.q3After,
        choices: s.q3Choices,
        correctChoice: s.q3Correct,
        hint: s.q3Hint,
        explanation: s.q3Exp,
        ltr: s.ltr,
      },
      {
        id: `${s.id}-e4`,
        type: 'classify',
        prompt: s.q4Prompt,
        binALabel: s.q4BinA,
        binBLabel: s.q4BinB,
        items: s.q4Items,
        hint: s.q4Hint,
        explanation: s.q4Exp,
        ltr: s.ltr,
      },
      {
        id: `${s.id}-e5`,
        type: 'order',
        prompt: s.q5Prompt,
        tokens: s.q5Tokens,
        correctOrder: s.q5Order,
        hint: s.q5Hint,
        explanation: s.q5Exp,
        ltr: s.ltr,
      },
    ],
  };
}

